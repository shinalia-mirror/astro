const form=document.getElementById("searchForm");
const input=document.getElementById("idInput");
const result=document.getElementById("result");
const status=document.getElementById("status");

function showPaper(id,p){
  result.classList.remove("hidden");
  result.innerHTML = `
    <div class="paper-head">
      <div class="paper-id">DOCUMENT ID : ${id}</div>
      <h1 class="paper-title">『${p.title}』</h1>
      <div class="paper-author">${p.author}</div>
    </div>
    <div class="paper-body">
      <div class="abstract-label">ABSTRACT</div>
      ${p.paragraphs.map(x=>`<p>${x}</p>`).join("")}
      ${p.note ? `<div class="break-note">${p.note}</div>` : ""}
      ${p.personal ? `<div class="personal-note">${p.personal}</div>` : ""}
    </div>`;
  result.scrollIntoView({behavior:"smooth",block:"start"});
}

function showAward(id,a){
  result.classList.remove("hidden");
  result.innerHTML=`
    <div class="award">
      <div class="paper-id">DOCUMENT ID : ${id}</div>
      <div style="margin-top:18px" class="award-badge">SPECIAL RECORD</div>
      <h1 class="award-title">${a.title}</h1>
      <div class="award-text">${a.text}</div>
    </div>`;
  result.scrollIntoView({behavior:"smooth",block:"start"});
}

form.addEventListener("submit",e=>{
  e.preventDefault();
  const id=input.value.trim();
  if(papers[id]){status.textContent="照会完了。";showPaper(id,papers[id]);return}
  if(award[id]){status.textContent="特殊記録を照会しました。";showAward(id,award[id]);return}
  result.classList.remove("hidden");
  result.innerHTML=`<div class="no-result"><strong>該当する文書が見つかりません。</strong>入力されたID「${id || "（未入力）"}」はデータベースに登録されていません。</div>`;
  status.textContent="照会結果：該当なし。";
  result.scrollIntoView({behavior:"smooth",block:"start"});
});
